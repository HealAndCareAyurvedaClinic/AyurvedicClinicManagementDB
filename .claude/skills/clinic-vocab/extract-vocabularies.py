"""
Extract the database's enum vocabularies from deploy/baseline-schema.sql.

Most of this schema's fixed value-sets are enforced only by a SQL Server CHECK
constraint. The API's OpenAPI document calls those columns `string`, so a value its
own DTO accepts can still be rejected by the database, and the error arrives as a
constraint violation rather than a validation message naming the allowed values.

This reads the baseline schema -- the only file that describes the live shape -- and
writes reference/vocabularies.md.

    python extract-vocabularies.py                 # from this directory
    python extract-vocabularies.py --check         # fail if the reference is stale

What it looks for, in ALTER TABLE ... WITH CHECK ADD [CONSTRAINT x] CHECK ((expr)):

  a vocabulary   ([col]='A' OR [col]='B' OR [col]=N'C')   one column, all equality
  a rule         anything else (ranges, cross-column conditions)

Rules are counted but not listed; they are not vocabularies and pretending otherwise
would bury the useful part.

The collision report at the end is the point. `medicine_type` means one thing on
encounter_prescriptions and a different thing on current_medications, which is not
visible from either column's name and has cost real time.
"""
import argparse
import pathlib
import re
import sys
from collections import defaultdict

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]                      # .claude/skills/clinic-vocab -> repo root
SCHEMA = REPO / "deploy" / "baseline-schema.sql"
OUT = HERE / "reference" / "vocabularies.md"

# ALTER TABLE [dbo].[t]  WITH CHECK ADD  CONSTRAINT [name] CHECK  ((expr))
CONSTRAINT = re.compile(
    r"ALTER\s+TABLE\s+\[dbo\]\.\[(?P<table>[^\]]+)\]\s+WITH\s+CHECK\s+ADD\s+"
    r"(?:CONSTRAINT\s+\[(?P<name>[^\]]+)\]\s+)?CHECK\s*\((?P<expr>.*?)\)\s*$",
    re.IGNORECASE | re.MULTILINE,
)
# [col]='value'  or  [col]=N'value'
EQUALITY = re.compile(r"\[(?P<col>[a-z0-9_]+)\]\s*=\s*N?'(?P<val>[^']*)'", re.IGNORECASE)


def parse(text):
    """-> ({(table, column): [values]}, rule_count)"""
    vocab, rules = {}, 0
    for m in CONSTRAINT.finditer(text):
        table, expr = m.group("table"), m.group("expr")
        pairs = EQUALITY.findall(expr)
        # A vocabulary is equality clauses on ONE column, joined by OR, and nothing else.
        stripped = EQUALITY.sub("", expr)
        leftover = re.sub(r"[()\s]|OR", "", stripped, flags=re.IGNORECASE)
        cols = {c.lower() for c, _ in pairs}
        if pairs and len(cols) == 1 and not leftover:
            col = cols.pop()
            # SQL Server scripts these in reverse; sort for a stable, readable file.
            vocab[(table, col)] = sorted({v for _, v in pairs})
        else:
            rules += 1
    return vocab, rules


def render(vocab, rules):
    by_table = defaultdict(list)
    for (table, col), values in vocab.items():
        by_table[table].append((col, values))

    by_name = defaultdict(set)
    for (table, col), values in vocab.items():
        by_name[col].add((table, tuple(values)))
    collisions = {c: v for c, v in by_name.items() if len({vals for _, vals in v}) > 1}

    L = []
    L.append("# Column vocabularies")
    L.append("")
    L.append("Generated by `extract-vocabularies.py` from `deploy/baseline-schema.sql`.")
    L.append("**Do not edit by hand** — rerun the script.")
    L.append("")
    L.append(f"{len(vocab)} columns restricted to a fixed set of values, across "
             f"{len(by_table)} tables. ({rules} further CHECK constraints express rules "
             "rather than vocabularies and are not listed.)")
    L.append("")
    L.append("Most of these are enforced **only** here. The API's OpenAPI document types "
             "them as `string`, so a value its DTO accepts can still be refused by the "
             "database.")
    L.append("")

    if collisions:
        L.append("## ⚠️ Same column name, different vocabulary")
        L.append("")
        L.append("Knowing the column name is not enough for these — the table decides "
                 "which set applies.")
        L.append("")
        for col in sorted(collisions):
            L.append(f"**`{col}`**")
            L.append("")
            for table, values in sorted(collisions[col]):
                L.append(f"- `{table}` → {', '.join('`%s`' % v for v in values)}")
            L.append("")

    L.append("## By table")
    L.append("")
    for table in sorted(by_table):
        L.append(f"### `{table}`")
        L.append("")
        for col, values in sorted(by_table[table]):
            L.append(f"- **`{col}`** — {', '.join('`%s`' % v for v in values)}")
        L.append("")
    return "\n".join(L).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the generated file is missing or out of date")
    args = ap.parse_args()

    if not SCHEMA.exists():
        sys.exit(f"schema not found: {SCHEMA}")

    vocab, rules = parse(SCHEMA.read_text(encoding="utf-8", errors="replace"))
    if not vocab:
        sys.exit("no vocabularies found — the schema format may have changed")
    content = render(vocab, rules)

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            # ASCII only: this line lands in CI logs and consoles that are not UTF-8.
            sys.exit(f"{OUT.relative_to(REPO)} is out of date - rerun "
                     "extract-vocabularies.py and commit the result")
        print(f"up to date: {len(vocab)} vocabularies")
        return

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(vocab)} vocabularies, {rules} rules skipped")


if __name__ == "__main__":
    main()
